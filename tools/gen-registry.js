#!/usr/bin/env node
/**
 * Scans src/features/&#42;/manifest.ts and writes src/core/registry/registry.generated.ts.
 * Gitignored on purpose — this is the one file that "knows about" every feature, and
 * generating it means adding a feature never means editing a shared file by hand.
 *
 * manifest.ts files must have no runtime imports (type-only imports are fine — they
 * erase at compile time), because we transpile+execute them here without a bundler.
 */
const fs = require("fs");
const path = require("path");
const ts = require("typescript");

const ROOT = path.resolve(__dirname, "..");
const FEATURES_DIR = path.join(ROOT, "src/features");
const OUT_FILE = path.join(ROOT, "src/core/registry/registry.generated.ts");

function loadManifest(manifestPath) {
  const source = fs.readFileSync(manifestPath, "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
    fileName: manifestPath,
  });

  const sandboxModule = { exports: {} };
  const fn = new Function("module", "exports", "require", outputText);
  fn(sandboxModule, sandboxModule.exports, () => {
    throw new Error(`${manifestPath}: manifest.ts must not have runtime imports.`);
  });

  const manifest = sandboxModule.exports.manifest;
  if (!manifest) throw new Error(`${manifestPath} must export a const named "manifest".`);
  return manifest;
}

function main() {
  const entries = fs
    .readdirSync(FEATURES_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name !== "_template")
    .map((entry) => entry.name)
    .sort();

  const manifests = [];
  for (const id of entries) {
    const manifestPath = path.join(FEATURES_DIR, id, "manifest.ts");
    if (!fs.existsSync(manifestPath)) {
      console.warn(`[gen-registry] skipping "${id}": no manifest.ts`);
      continue;
    }
    const manifest = loadManifest(manifestPath);
    if (manifest.id !== id) {
      throw new Error(`${manifestPath}: manifest.id ("${manifest.id}") must match folder name ("${id}").`);
    }
    manifests.push(manifest);
  }

  manifests.sort((a, b) => a.order - b.order);

  const banner = "// AUTO-GENERATED by tools/gen-registry.js — do not edit by hand.\n";
  const body =
    banner +
    'import type { FeatureManifest } from "./types";\n\n' +
    `export const features: FeatureManifest[] = ${JSON.stringify(manifests, null, 2)};\n`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body);
  console.log(`[gen-registry] wrote ${manifests.length} feature(s) to ${path.relative(ROOT, OUT_FILE)}`);
}

main();
